#!/usr/bin/env python3
"""
Emit physics_data.h for the Vita app from the RECOVERED game data:

  - per-car scalars from Settings/<group><n>.crs, converted to physical units
    with the scale constants recovered from the loaders (scales_table.py)
  - per-car acceleration curves from Splines/splAccelBase<n>.bspl
  - the steering response curve from Splines/steering<n>.bspl

These are the game's real numbers. The MODEL that consumes them in physics.c
is NOT the game's integrator -- that is still untranscribed (see PHYSICS.md).

Usage: python3 gen_physics_header.py > ../rccars_vita/physics_data.h
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bspl2csv
import dump_physics as DP

SET = "/mnt/c/tools/rccars_extracted/Settings"
SPL = "/mnt/c/tools/rccars_extracted/Splines"

WANT = [
    ("speedBaseMax", "speed_base_max"), ("speedBoostMax", "speed_boost_max"),
    ("boostSpeedUp", "boost_up"), ("boostSpeedDown", "boost_down"),
    ("coeffAirResistance", "air_drag"), ("coeffFrictionBearings", "bearing_friction"),
    ("CoeffFrontTires", "grip_front"), ("CoeffRearTires", "grip_rear"),
    ("coeffDriftRear", "drift_rear"), ("angleDriftOn", "drift_angle_on"),
    ("speedDriftOn", "drift_speed_on"),
    ("coeffDeepSand", "coeff_sand"), ("coeffWater", "coeff_water"),
    ("AngleSteer", "steer_max_deg"),
    ("kPos", "susp_k_pos"), ("kSpeed", "susp_k_speed"),
    ("length", "susp_length"), ("lenMin", "susp_len_min"), ("lenMax", "susp_len_max"),
    ("coeffMomentOX", "moment_ox"), ("coeffMomentOZ", "moment_oz"),
    ("lenAxe", "len_axe"), ("touchPoint", "touch_point"),
]


def car_params(n):
    vals = {}
    for g in DP.GROUPS:
        crs = os.path.join(SET, f"{g}{n}.crs")
        if not os.path.exists(crs):
            continue
        for name, (lo, hi, raw) in DP.read_crs(crs).items():
            sc = DP.SCALES.get(name)
            vals[name] = ((raw - sc[0]) * sc[1] + sc[2]) if sc else float(raw)
    return vals


def curve(path):
    cs = bspl2csv.decode(path)
    if not cs:
        return []
    return [(p[1], p[2]) for p in cs[0]]


def main():
    print("/* Generated by gen_physics_header.py -- do not edit.")
    print(" * Values recovered from RC Cars' own Settings/*.crs and Splines/*.bspl,")
    print(" * converted to physical units using the loader scale constants.")
    print(" * See rccars_re/PHYSICS.md. */")
    print("#ifndef PHYSICS_DATA_H\n#define PHYSICS_DATA_H\n")
    print("typedef struct { float in, out; } curve_pt_t;\n")
    print("typedef struct {")
    print("    const char *name;")
    for _, c in WANT:
        print(f"    float {c};")
    print("    const curve_pt_t *accel;  int accel_n;")
    print("    const curve_pt_t *steer;  int steer_n;")
    print("} car_phys_t;\n")

    for n in (1, 2, 3):
        for kind, f in (("accel", f"splAccelBase{n}.bspl"), ("steer", f"steering{n}.bspl")):
            pts = curve(os.path.join(SPL, f))
            print(f"static const curve_pt_t {kind}{n}[] = {{", end="")
            print(", ".join(f"{{{a:.6f}f,{b:.6f}f}}" for a, b in pts), end="")
            print("};")
    print()

    print("static const car_phys_t CARS[3] = {")
    for n in (1, 2, 3):
        v = car_params(n)
        print(f'  {{ "{DP.CARS[n]}",')
        for key, cname in WANT:
            print(f"    /* {cname:<18} */ {v.get(key, 0.0):.6f}f,")
        print(f"    accel{n}, (int)(sizeof(accel{n})/sizeof(curve_pt_t)),")
        print(f"    steer{n}, (int)(sizeof(steer{n})/sizeof(curve_pt_t)) }},")
    print("};\n")
    print("#endif")


if __name__ == "__main__":
    main()
