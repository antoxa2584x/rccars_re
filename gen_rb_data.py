#!/usr/bin/env python3
"""
Emit rb_data.h for the Vita app: everything rb_tuning needs, from the game's own
data, with the conversions as they are actually applied by the loaders.

This supersedes gen_physics_header.py for the transcribed model. The differences
matter, and each is a correction rather than a refinement:

  * the engine curve is <CAR>.bspl, NOT splAccelBase<n>.bspl. The engine reads
    engine[6], which physLoadEngine fills from "OVERKILL" / "BUGGY" / "HUMMER";
    splAccelBase is a different curve that the engine never evaluates.
    <CAR>_RESTRICT.bspl is engine[5] and becomes engine braking.
  * lenMin and lenMax are FRACTIONS of `length` -- physLoadSprings seeds each
    slot from `length` and multiplies.
  * kPos is a fraction of (length - lenMin) and is the STATIC SAG IN METRES, not
    a spring rate. carSetupSprings derives the stiffness from it as
    (mass*10)/(nwheels*sag).
  * every CdtDelta* / CdtRadUp* key carries an extra x0.1 that physLoadCdt
    applies on top of the slider conversion.
  * the upgrade tables come from Scripts/upgrades.ini, not the .crs files:
    [TIRES] scales grip, [RESONATORS] <Car>Upgrades scales top speed and
    <Car>Upgrades_SPL_OY scales acceleration.

See rccars_re/PHYSICS.md.

Usage: python3 gen_rb_data.py > ../rccars_vita/rb_data.h
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bspl2csv
import car_geom
import dump_physics as DP

EXTRACT = "/mnt/c/tools/rccars_extracted"
SET = os.path.join(EXTRACT, "Settings")
SPL = os.path.join(EXTRACT, "Splines")
UPG = os.path.join(EXTRACT, "Scripts", "upgrades.ini")

CAR_SPLINE = {1: "OVERKILL", 2: "BUGGY", 3: "HUMMER"}
CAR_UPG = {1: "Overkill", 2: "Buggy", 3: "Hummer"}

# keys the loader multiplies by 0.1 after the slider conversion (physLoadCdt)
CDT_SCALED = re.compile(r"^(CdtDelta[XYZ]|CdtDeltaZ_CENTRAL|CdtRadUp)\d?$")


def raw_and_scaled(n):
    """Return (raw, scaled) dicts for one car across all six groups."""
    raw, scaled = {}, {}
    for g in DP.GROUPS:
        crs = os.path.join(SET, f"{g}{n}.crs")
        if not os.path.exists(crs):
            continue
        for name, (lo, hi, v) in DP.read_crs(crs).items():
            raw[name] = float(v)
            sc = DP.SCALES.get(name)
            scaled[name] = ((v - sc[0]) * sc[1] + sc[2]) if sc else float(v)
    return raw, scaled


def curve(fname):
    path = os.path.join(SPL, fname)
    if not os.path.exists(path):
        return []
    cs = bspl2csv.decode(path)
    return [(p[1], p[2]) for p in cs[0]] if cs else []


def upgrades():
    """Parse Scripts/upgrades.ini -> {section: {key: [floats]}}."""
    out, sec = {}, None
    if not os.path.exists(UPG):
        return out
    for line in open(UPG, encoding="latin-1"):
        m = re.match(r'\s*Section\s+Keys\s+"([^"]+)"', line)
        if m:
            sec = m.group(1)
            out[sec] = {}
            continue
        if re.match(r"\s*End", line):
            sec = None
            continue
        m = re.match(r"\s*(\w+)\s*\(float\[\d+\]\)\s*=\s*(.+)", line)
        if m and sec:
            out[sec][m.group(1)] = [float(x) for x in m.group(2).split(",")]
    return out


def cdt_val(raw, scaled, key, default=0.0):
    """Apply physLoadCdt's extra x0.1 where the loader does."""
    if key not in scaled:
        return default
    v = scaled[key]
    if CDT_SCALED.match(key):
        v *= 0.1
    return v


def emit_curve(name, pts):
    if not pts:
        print(f"static const rb_curve_pt {name}[] = {{ {{0.0f,0.0f}} }};")
        return 1
    body = ", ".join(f"{{{a:.6f}f,{b:.6f}f}}" for a, b in pts)
    print(f"static const rb_curve_pt {name}[] = {{{body}}};")
    return len(pts)


def main():
    up = upgrades()

    print("/* Generated by rccars_re/gen_rb_data.py -- do not edit.")
    print(" *")
    print(" * Per-car tuning for the transcribed model (rb.c / contact.c /")
    print(" * collide.c), taken from the game's own Settings, Splines and")
    print(" * Scripts/upgrades.ini with the conversions the loaders actually")
    print(" * apply. See rccars_re/PHYSICS.md. */")
    print("#ifndef RB_DATA_H\n#define RB_DATA_H\n")
    print('#include "rb.h"\n')

    counts = {}
    for n in (1, 2, 3):
        s = CAR_SPLINE[n]
        counts[("accel", n)] = emit_curve(f"rb_accel{n}", curve(f"{s}.bspl"))
        counts[("restr", n)] = emit_curve(f"rb_restr{n}", curve(f"{s}_RESTRICT.bspl"))
    print()

    print("/* Geometry and mass are NOT in the .crs files -- the original takes")
    print(" * them from the car's mesh and its cdt block. These are measured from")
    print(" * the extracted models (see rccars_obj) with lenAxe as the half-track.")
    print(" */")
    print("typedef struct {")
    print("    const char *name;")
    print("    int   nwheels;")
    print("    float mass;")
    print("    float extent[3];      /* box extents for the inertia tensor */")
    print("    float half_track;     /* lenAxe */")
    print("    float half_base;      /* from the mesh */")
    print("    float mount_y;")
    print("    /* CenterMassOY (cdt[42]): how far ABOVE THE MODEL ORIGIN the rigid")
    print("     * body's own origin -- the centre of mass -- sits. It is the")
    print("     * model-space -> body-space shift, so main.c draws the model with")
    print("     * glTranslatef(0, -com_oy, 0) and every body-space constant taken")
    print("     * off the mesh comes down by it.")
    print("     *")
    print("     * RECOVERED. physLoadCdt reads it at")
    print("     * 0x004f9010(0, 0.2, 1.0, 100.0, raw) -- a clamped 1..100 -> 0..0.2 m")
    print("     * remap, and unlike every CdtDelta/CdtRadUp key it takes NO extra")
    print("     * x0.1 -- and stores it at DAT_014c4da8 + car*0x2d*4. FUN_004f1150")
    print("     * hands it out as the vector (0, com_oy, 0). FUN_00474f70 ADDS that")
    print("     * vector, rotated by the model's own basis, to a model transform to")
    print("     * get the body's; FUN_00475030 negates it first (fchs at 0x475078,")
    print("     * 0x475083, 0x47508c) to go back the other way. Those two are the")
    print("     * original's own version of main.c's glTranslatef, and between them")
    print("     * they settle both the meaning and the sign. */")
    print("    float com_oy;")
    print("    float steer_max_deg;  /* AngleSteer */")
    print("    rb_tuning tune;")
    print("    float len_free, len_min, len_max, sag, k_speed, radius;")
    print("} rb_car_data;\n")

    # ---- the boost meter's capacity scale --------------------------------
    #
    # FUN_0050b7f0 turns the car's booster strength into the capacity of the
    # boost meter, remapping it onto 50..100 against a fixed reference range and
    # rounding to a whole number:
    #
    #     T  = boostSpeedUp(car)     * BOOSTERS[car][level]
    #     lo = boostSpeedUp(Buggy)   * BOOSTERS[Hummer][0]      <- 0x50b854
    #     hi = boostSpeedUp(Hummer)  * BOOSTERS[Hummer][3]      <- 0x50b873
    #     T < lo -> 50 ; T > hi -> 100 ; |hi-lo| < 1e-6 -> 0
    #     else  (T - lo) * 50/(hi - lo) + 50, then floor(x + 0.5)
    #
    # NOTE THE MIXED CARS in `lo`: the original pairs car 1's fill rate with car
    # 2's level-0 multiplier -- the `push` arguments to cfgEngineParams either
    # side of that multiply are 1 and 2 -- where every other term pairs a car
    # with its own row. It is invisible in the shipped data (the Buggy and the
    # Hummer carry identical [BOOSTERS] rows, and all three cars carry
    # boostSpeedUp 1.5), so it is transcribed as written rather than
    # "corrected". The bounds then land on exactly the level-0 and level-3
    # products, which is what puts the endpoints on a clean 50 and 100.
    #
    # These are two GLOBAL numbers, not per-car ones. They are emitted into each
    # car's rb_tuning anyway, so the model layer (rb.c / contact.c) needs no
    # access to the car table -- the same reason boost_ratio is carried there
    # rather than divided out at the point of use.
    def _boost_ref(rate_car, table_car, lvl):
        _, s = raw_and_scaled(rate_car)
        row = up.get("BOOSTERS", {}).get(f"{CAR_UPG[table_car]}Upgrades",
                                         [1, 1, 1, 1])
        return s.get("boostSpeedUp", 1.5) * row[lvl]

    ref_lo = _boost_ref(2, 3, 0)
    ref_hi = _boost_ref(3, 3, 3)

    print("static const rb_car_data RB_CARS[3] = {")
    for n in (1, 2, 3):
        raw, sc = raw_and_scaled(n)
        u_t = up.get("TIRES", {}).get(f"{CAR_UPG[n]}Upgrades", [1, 1, 1, 1])
        u_rs = up.get("RESONATORS", {}).get(f"{CAR_UPG[n]}Upgrades", [1, 1, 1, 1])
        u_ra = up.get("RESONATORS", {}).get(f"{CAR_UPG[n]}Upgrades_SPL_OY",
                                           [1, 1, 1, 1])
        u_b = up.get("BOOSTERS", {}).get(f"{CAR_UPG[n]}Upgrades", [1, 1, 1, 1])

        length = sc.get("length", 0.0)
        len_min = sc.get("lenMin", 0.1) * length
        len_max = sc.get("lenMax", 1.1) * length
        # kPos: ((raw-1)*0.0080808 + 0.1) * (length - lenMin)
        sag = ((raw.get("kPos", 1.0) - 1.0) * 0.0080808 + 0.1) * (length - len_min)
        rad_wheel = cdt_val(raw, sc, "CdtRadWheel", 0.07)
        nwheels = 6 if n == 3 else 4

        # Mesh-derived, from RCCarsDB/Car.sb.
        #
        # The Buggy and Hummer used to be handed the Overkill's numbers, because
        # only its LOD3 subtree carries unrotated wheel translations and the other
        # two "would need hierarchy composition". They now get their own, measured
        # by car_geom.composed(): the 0x540B Euler order in sb2obj was building
        # Rx*Ry*Rz where the engine's own modpTRSCalcLTM builds Rz*Ry*Rx, which is
        # exactly what made those chains uncomposable. The Hummer's wheelbase was
        # the worst of it -- 0.146 against a real 0.1825, 25% short -- and its
        # track 0.141 against 0.1702.
        #
        # Car 1 is deliberately LEFT ON ITS OLD NUMBERS. They are the LOD3 mesh
        # measured in the node's own space, i.e. before the uniform 1.05 scale the
        # car chains carry, so they run about 5% small (composition gives
        # half_track 0.1528, half_base 0.1543, body 0.147 x 0.111 x 0.443). Every
        # figure pinned in PHYSICS.md and rb_test.c -- the ride height, the
        # 6.90 m/s limiter, the slope sweep, the 131 mm porpoise -- was measured
        # against these, and geometry is documented as the single most influential
        # input to the friction solve. Moving it is a deliberate step with a
        # re-measurement behind it, not a side effect of fixing the other two.
        CG = car_geom.composed()
        # Car 1 keeps its LOD3 numbers (see above), but the fourth element --
        # the wheel-centre plane's height in the model -- is taken from the
        # composed tree like the other two. It is not a physics dimension: it is
        # only the model-space -> body-space shift for the cdt offsets, and the
        # model it has to agree with is the PACKED, composed one. It matches
        # carani_wheel_plane_y off car1.vsc to four decimals (0.0567).
        GEOM = {1: (0.1410, 0.1490, (0.140, 0.106, 0.422),
                    CG.get("Overkill", {}).get("wheel_y", 0.0),
                    CG.get("Overkill", {}).get("box"))}
        for _i, _nm in ((2, "Buggy"), (3, "Hummer")):
            _g = CG.get(_nm)
            if not _g or "half_track" not in _g or not _g["extent"]:
                raise SystemExit(f"car_geom.composed(): no geometry for {_nm}")
            GEOM[_i] = (_g["half_track"], _g["half_base"], _g["extent"],
                    _g["wheel_y"], _g["box"])
        half_track_mesh, half_base, extent, wheel_y, shell = GEOM[n]
        if not shell:
            raise SystemExit(f"car_geom.composed(): no ENVIR_CAR_BODY box for car {n}")
        # CenterMassOY, in metres above the model origin: 0.0000 on the Overkill,
        # 0.0323 on the other two. The Overkill's raw is 1, the BOTTOM of the
        # 1..100 slider, where the .ini's own default is 17 -- so its com was
        # deliberately dragged to the floor and the other two were left alone.
        com_oy = sc.get("CenterMassOY", 0.0)
        # ENVIR_CAR_BODY in the BODY FRAME, which is now the ENGINE'S body frame:
        # model space shifted down by com_oy. Car 1's `extent` above is
        # deliberately its pre-1.05-scale LOD3 size (see the note there);
        # `shell_lo/hi` is the COMPOSED, scaled box, which is the one packed into
        # car1.vsc and actually drawn. For the Overkill the two differ by that 5%.
        shell_lo = (shell[0][0], shell[0][1] - com_oy, shell[0][2])
        shell_hi = (shell[1][0], shell[1][1] - com_oy, shell[1][2])
        # Where the ground is in body space when the car is parked: the wheel
        # centres rest at `wheel_y - com_oy` (mount_y below is built to put them
        # exactly on the model's own wheel nodes) and the ground is one wheel
        # radius under that. It used to be simply -rad_wheel, because the com was
        # ON the wheel-centre plane; every clearance test below needs the general
        # form now.
        ground_y = wheel_y - com_oy - rad_wheel

        print(f'  {{ "{DP.CARS[n]}",')
        print(f"    /* nwheels        */ {nwheels},")
        print(f"    /* mass           */ 2.000000f,")
        print(f"    /* extent         */ {{{extent[0]:.6f}f,{extent[1]:.6f}f,{extent[2]:.6f}f}},")
        # lenAxe (0.089) is the physics half-track and is NARROWER than the
        # mesh (0.141); the original uses the mesh position for the mount and
        # lenAxe elsewhere. Use the mesh.
        print(f"    /* half_track     */ {half_track_mesh:.6f}f,")
        print(f"    /* half_base      */ {half_base:.6f}f,")
        # The com sits `com_oy` above the MODEL origin, so a wheel resting on the
        # model's own wheel-centre plane is at body y = wheel_y - com_oy, and the
        # mount is one rest length above that. This used to be a bare
        # `length - sag`, i.e. the com parked ON the wheel-centre plane, which put
        # it 57 / 29 / 39 mm too high; the vertical lever arm from the com to the
        # contact patch enters the friction matrix as ry^2 * Izz_inv, so that is a
        # handling change and not a relabelling.
        #
        # Note what this construction buys: the resting wheel centre in body space
        # is exactly the mesh's own wheel node, so the drawn wheels sit on the
        # physics wheels with no fudge -- the alignment main.c used to have to
        # arrange by dropping the model onto the mean wheel plane now falls out.
        print(f"    /* mount_y        */ {(wheel_y - com_oy + length - sag):.6f}f,")
        print(f"    /* com_oy         */ {com_oy:.6f}f,")
        print(f"    /* steer_max_deg  */ {sc.get('AngleSteer', 30.0):.6f}f,")
        print("    { /* tune */")
        print(f"      /* moment_ox     */ {sc.get('coeffMomentOX', 1.0):.6f}f,")
        print(f"      /* moment_oz     */ {sc.get('coeffMomentOZ', 1.0):.6f}f,")
        # springs[11], lenAxe. Only the visual axle angle (carAniProc1
        # 0x00504820) uses it; the physics half-track comes from the mesh.
        print(f"      /* len_axe       */ {sc.get('lenAxe', 0.089):.6f}f,")
        # springs[12] / springs[13], the Buggy wishbone's angle clamp, degrees.
        # Both are read through the 1..100 -> 0..90 remap at 0x004f9804 and
        # 0x004f9882, which CLAMPS at both ends (0x004f9010). The raw is 0 on
        # cars 1 and 3 -- below the slider's own minimum -- so the value the
        # engine ends up holding there is 0.0, not the -0.909 the unclamped
        # line gives. Only carAniProc2 reads them; see carani.c.
        print(f"      /* angle_up      */ "
              f"{min(max(sc.get('angleProcUpMax', 0.0), 0.0), 90.0):.6f}f,")
        print(f"      /* angle_down    */ "
              f"{min(max(sc.get('angleProcDownMax', 0.0), 0.0), 90.0):.6f}f,")
        print(f"      /* bearings      */ {sc.get('coeffFrictionBearings', 0.0):.6f}f,")
        print(f"      /* air_res       */ {sc.get('coeffAirResistance', 0.0):.6f}f,")
        print(f"      /* front_tires   */ {sc.get('CoeffFrontTires', 0.7):.6f}f,")
        print(f"      /* rear_tires    */ {sc.get('CoeffRearTires', 0.7):.6f}f,")
        print(f"      /* angle_drift   */ {sc.get('angleDriftOn', 1.0):.6f}f,")
        print(f"      /* speed_drift   */ {sc.get('speedDriftOn', 1.0):.6f}f,")
        print(f"      /* drift_rear    */ {sc.get('coeffDriftRear', 1.0):.6f}f,")
        print(f"      /* deep_sand     */ {sc.get('coeffDeepSand', 0.0):.6f}f,")
        print(f"      /* water         */ {sc.get('coeffWater', 0.0):.6f}f,")
        print("      /* tire_upgrade  */ {" +
              ",".join(f"{x:.6f}f" for x in u_t[:4]) + "},")
        # tire[12], SpeedAngMaxREL. physLoadTires reads it with the FLOAT getter
        # (0x00404950), which leaves its target untouched when the key is absent
        # -- and no shipped tires<n>.crs carries it, so the global keeps its BSS
        # zero. dump_physics only sees the .crs, so 0.0 is the retail value.
        print(f"      /* spin_extra    */ {sc.get('SpeedAngMaxREL', 0.0):.6f}f,")
        # engine[0] and engine[1]. The .ini's own key names say what they are:
        # the rates the boost meter fills and empties at, in meter units per
        # second. FUN_004f3800 is the meter, and it is the only consumer of the
        # [BOOSTERS] table -- see booster_upgrade just below.
        print(f"      /* boost_up      */ {sc.get('boostSpeedUp', 1.5):.6f}f,")
        print(f"      /* boost_down    */ {sc.get('boostSpeedDown', 5.454545):.6f}f,")
        print(f"      /* speed_base    */ {sc.get('speedBaseMax', 27.0):.6f}f,")
        print(f"      /* speed_boost   */ {sc.get('speedBoostMax', 35.0):.6f}f,")
        base = sc.get("speedBaseMax", 27.0)
        boost = sc.get("speedBoostMax", 35.0)
        print(f"      /* boost_ratio   */ {(boost / base if base else 1.0):.6f}f,")
        # engine[7..10], at config-block offsets 0x1c..0x28 -- between the two
        # curves and the [RESONATORS] pair, exactly where the other two upgrade
        # tables live. FUN_004f3800 reads it as
        #     [cfgEngineParams(car) + 0x1c + boost*4]
        # with `boost` the level at phys+0xe458+car*0xb0, the slot between the
        # resonator level (0xe454) and the tire level (0xe45c).
        print("      /* booster_upg   */ {" +
              ",".join(f"{x:.6f}f" for x in u_b[:4]) + "},")
        print(f"      /* boost_ref_lo  */ {ref_lo:.6f}f,")
        print(f"      /* boost_ref_hi  */ {ref_hi:.6f}f,")
        print("      /* reso_speed    */ {" +
              ",".join(f"{x:.6f}f" for x in u_rs[:4]) + "},")
        print("      /* reso_accel    */ {" +
              ",".join(f"{x:.6f}f" for x in u_ra[:4]) + "},")
        print(f"      /* accel curve   */ {{ rb_accel{n}, {counts[('accel', n)]} }},")
        print(f"      /* restrict      */ {{ rb_restr{n}, {counts[('restr', n)]} }},")
        print(f"      /* cdt_rad_wheel */ {rad_wheel:.6f}f,")
        rb = sc.get("coeffRadBackWheels", 1.0) * rad_wheel
        print(f"      /* cdt_rad_back  */ {rb:.6f}f,")
        # FrontWheelDeltaX has no recovered slider scale, and cdt[15] is not
        # written by the visible part of physLoadCdt. Emitting the raw value
        # scaled by 0.1 gives 1.2 m, which is absurd for a 1:10 car, so emit 0
        # until the conversion is known.
        print("      /* cdt_front_x   */ 0.000000f,  /* FrontWheelDeltaX: scale unrecovered */")
        print(f"      /* cdt_side_x    */ {sc.get('shiftRoofBaseLefter', 0.05):.6f}f,")
        print("      /* body_sphere   */ {")
        side_x = sc.get("shiftRoofBaseLefter", 0.05)
        for k in range(3):
            sfx = "" if k == 0 else str(k + 1)
            # Slots 2 and 3 are absent from every shipped .crs, and the engine's
            # own globals for them sit in the zero-filled part of .data, so the
            # ORIGINAL skips them too -- a retail car really is 7 spheres, not
            # the 13 rb_gather_spheres' header describes. What the engine calls
            # them is the tell though: shiftRoofBaseLefter, ROOF base. Slot 0 is
            # the chassis station and 2/3 are the roof.
            #
            # THE PORT'S, and the reason it cannot just leave them absent: with
            # only the chassis station, a car on its roof has nothing under the
            # roof to stand on. Measured against the drawn shell, an inverted car
            # buried 97 mm of Overkill, 64 mm of Buggy and 104 mm of Hummer --
            # for the Overkill that is its whole 111 mm shell, underground. The
            # original does not reach that state anything like as badly because
            # its own roof stations are real data that this retail .crs simply
            # does not carry; CenterMassOY being recovered now fixes the FRAME
            # these sit in but supplies no offsets, so they are still fitted to
            # the one thing that is not in doubt -- where ENVIR_CAR_BODY's own
            # roof is.
            #
            # Two stations, fore and aft, each set a radius in from its end of
            # the shell so the pair spans it; the x = 0 base lets the three
            # passes in rb_gather_spheres straddle the centre line. The radius is
            # the recovered CdtRadUp, so the whole proxy keeps one radius.
            #
            # What this deliberately does NOT do is reach any further out than
            # the wheels. At 90 degrees of roll the roof spheres reach |x| 0.10
            # against the wheels' 0.21, so the car still balances on the outer
            # edges of its tyres and carJump's reset still correctly declines in
            # the 80-100 degree band. Only at a real flip do they take the load.
            if ("CdtRadUp" + sfx) not in sc:
                if k == 0:
                    print("        { {0.000000f,0.000000f,0.000000f}, 0.000000f, "
                          "0.000000f },  /* absent */")
                    continue
                rr = cdt_val(raw, sc, "CdtRadUp", 0.05)
                oy = shell_hi[1] - rr
                oz = (shell_lo[2] + rr) if k == 1 else (shell_hi[2] - rr)
                # It must clear the ground when the car is the right way up.
                if oy - rr <= ground_y:
                    raise SystemExit(
                        f"car {n}: roof station {k} hangs to {oy - rr:.4f}, "
                        f"at or below the ground at {ground_y:.4f}")
                # And the two stations must not collapse into one another.
                if k == 2 and shell_hi[2] - shell_lo[2] <= 2.0 * rr:
                    raise SystemExit(f"car {n}: shell too short for two roof stations")
                over = side_x + rr - shell_hi[0]
                note = ("  /* THE PORT'S: roof, %s%s */"
                        % ("aft" if k == 1 else "fore",
                           "" if over <= 0.0 else ", %.0f mm proud" % (over * 1000.0)))
                print(f"        {{ {{0.000000f,{oy:.6f}f,{oz:.6f}f}}, {rr:.6f}f, "
                      f"0.000000f }},{note}")
                continue
            ox = cdt_val(raw, sc, "CdtDeltaX" + sfx, 0.0)
            oy = cdt_val(raw, sc, "CdtDeltaY" + sfx, 0.0)
            oz = cdt_val(raw, sc, "CdtDeltaZ" + sfx, 0.0)
            # MODEL SPACE -> the port's BODY SPACE, and the shift is com_oy.
            #
            # carGatherCollSpheres (0x4ef9e0) builds each sphere as
            # row0*X + row1*Y + row2*Z + pos out of the matrix at phys+0xf8, whose
            # translation is phys+0x128. THAT MATRIX IS THE MODEL'S, NOT THE
            # BODY'S: FUN_0044c8e0 is the only thing that writes it (0x44c8f7,
            # through the matrix helper at 0x40c940) and it goes straight on to
            # copy the same 16 floats into the render node at *(phys+0x10)+0xac.
            # So these offsets are measured from the MODEL origin, and the port's
            # body origin is com_oy above it.
            #
            # Worth stating because getting it backwards is easy and cost a pass
            # here: the SAME vector runs the other way one function along.
            # FUN_00474f70(rb, phys+0xf8, (0,com_oy,0)) READS that model matrix
            # and writes the rigid body's own position, so the com is
            # model + com_oy while the spheres stay on the model. Two different
            # origins, one offset between them, and only the body's moved.
            #
            # This used to subtract `wheel_y`, which was the right shift for the
            # frame gen_rb_data.py used to build (com on the mesh's wheel-centre
            # plane) and is the wrong one now. The Overkill is unaffected either
            # way -- its CenterMassOY is 0.
            oy -= com_oy
            rr = cdt_val(raw, sc, "CdtRadUp" + sfx, 0.05)
            cz = cdt_val(raw, sc, "CdtDeltaZ_CENTRAL" + sfx, 0.0)
            # THE PORT'S, and what is left of it after the frame was fixed. In
            # the right frame the recovered Y is no longer absurd: the chassis
            # station lands at body y 0.0879 on the Overkill and 0.0737 on the
            # Hummer, both between the parked ground line and the underside of
            # ENVIR_CAR_BODY, i.e. exactly where a chassis blob belongs, and
            # neither is clamped in Y at all now. Two things still do not survive:
            #
            #  - X is |0.215| on all three cars against shell half-widths of
            #    0.0735 / 0.108 / 0.0971, and it is the SAME raw 16 on all three
            #    where the .ini's own default is 50 (which converts to -0.003,
            #    i.e. centred). Whatever that column means it is not a lateral
            #    offset in metres, so it is clamped to the shell.
            #  - the Buggy's Y is genuinely below its own ground line -- raw 42
            #    converts to -0.0515, and the shift that could rescue it is the
            #    one that is now known to be zero. The floor guard below catches
            #    it.
            #
            # Clamp into the REAL corners of ENVIR_CAR_BODY rather than
            # +/-extent/2. The old +/-extent/2 was a box centred on the body
            # origin and no car's shell is: with the frame corrected it would now
            # clamp the Overkill's perfectly good 0.0879 DOWN to 0.053, i.e.
            # invent a move where the data needs none. Anchored to the mesh, not
            # to a typed-in number.
            cl = []
            if ox < shell_lo[0]: ox = shell_lo[0]; cl.append("X")
            if ox > shell_hi[0]: ox = shell_hi[0]; cl.append("X")
            if oz < shell_lo[2]: oz = shell_lo[2]; cl.append("Z")
            if oz > shell_hi[2]: oz = shell_hi[2]; cl.append("Z")
            if oy > shell_hi[1]: oy = shell_hi[1]; cl.append("Y")
            # And it must not hang below the WHEELS, or the car parks on its
            # belly instead of its suspension: keep the sphere's bottom a fifth
            # of its own radius clear of the parked ground line. The Buggy needs
            # this on its own -- its body sphere (0.051) is almost as big as its
            # front wheel (0.049), so there is no height inside its shell where
            # the sphere misses the ground by accident.
            floor_y = ground_y + rr + 0.2 * rr
            if oy < floor_y:
                oy = floor_y
                cl.append("Y>floor")
            note = ("  /* " + " ".join(cl) + " clamped */") if cl else ""
            print(f"        {{ {{{ox:.6f}f,{oy:.6f}f,{oz:.6f}f}}, {rr:.6f}f, {cz:.6f}f }},{note}")
        print("      },")
        print("    },")
        print(f"    /* len_free */ {length:.6f}f,")
        print(f"    /* len_min  */ {len_min:.6f}f,")
        print(f"    /* len_max  */ {len_max:.6f}f,")
        print(f"    /* sag      */ {sag:.6f}f,")
        print(f"    /* k_speed  */ {sc.get('kSpeed', 1.0):.6f}f,")
        print(f"    /* radius   */ {rad_wheel:.6f}f }},")
    print("};\n")


    # ---- camera: Settings/Camera.crs, one global config (not per car) ----
    cam = {}
    cpath = os.path.join(SET, "Camera.crs")
    if os.path.exists(cpath):
        for name, (lo, hi, v) in DP.read_crs(cpath).items():
            cam[name] = float(v)

    def clampmap(raw, scale, off, lo, hi):
        v = (raw - 1.0) * scale + off
        return lo if raw < 1.0 else (hi if raw > 100.0 else v)

    dist_xz  = clampmap(cam.get("defDistXZ", 30.0), 0.01010101, 0.5, 0.5, 1.5)
    dist_y   = clampmap(cam.get("defDistY", 30.0), 0.009090909, 0.1, 0.1, 1.0)
    acc_y    = clampmap(cam.get("accDistY", 1.0), 0.019191919, 0.1, 0.1, 2.0)
    acc_a    = clampmap(cam.get("accAlpha", 50.0), 0.01010101, 0.0, 0.0, 1.0)
    vis_turn = clampmap(cam.get("VisTurn", 70.0), 0.6060606, -30.0, -30.0, 30.0)

    print("/* Camera, from Settings/Camera.crs via physLoadCamera (0x004f9da0).")
    print(" * The conversions are that function's own clamped affine maps. */")
    print("typedef struct {")
    print("    float dist_xz;     /* defDistXZ, metres behind */")
    print("    float dist_y;      /* defDistY, metres above */")
    print("    float acc_dist_y;  /* accDistY, vertical pull-back per second */")
    print("    float acc_alpha;   /* accAlpha, yaw pull-back scale */")
    print("    float vis_turn;    /* VisTurn, degrees of look-into-turn */")
    print("} rb_camera_data;\n")
    print("static const rb_camera_data RB_CAMERA = {")
    print("    /* dist_xz    */ %.6ff,   /* raw %d */" % (dist_xz, cam.get("defDistXZ", 30)))
    print("    /* dist_y     */ %.6ff,   /* raw %d */" % (dist_y, cam.get("defDistY", 30)))
    print("    /* acc_dist_y */ %.6ff,   /* raw %d */" % (acc_y, cam.get("accDistY", 1)))
    print("    /* acc_alpha  */ %.6ff,   /* raw %d */" % (acc_a, cam.get("accAlpha", 50)))
    print("    /* vis_turn   */ %.6ff    /* raw %d */" % (vis_turn, cam.get("VisTurn", 70)))
    print("};\n")
