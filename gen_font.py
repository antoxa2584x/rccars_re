#!/usr/bin/env python3
"""
Bake a monospace font into `font.h` for the Vita app's menu.

RC Cars has no reusable font asset -- `Faces/` and `FacesSys/` are the player
avatar portraits, and `Interface.sb` carries only dialog skins (buttons, panels,
scrollbars), no glyphs. The game's own text is drawn from something outside the
scene databases. Rather than reverse that for a debug menu, this bakes ASCII
32..126 into a small alpha atlas compiled into the binary, so the app needs no
extra file and the menu cannot fail to load.

The atlas is one row of 95 cells, `CELL_W x CELL_H` each, one byte of coverage
per texel. The app uploads it as GL_ALPHA and draws each glyph as a textured
quad, which is all vitaGL's fixed-function path needs.

Usage: python3 gen_font.py <out font.h> [--size 16] [--font PATH]
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126

CANDIDATES = [
    "/mnt/c/Windows/Fonts/consola.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/mnt/c/Windows/Fonts/cour.ttf",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--size", type=int, default=18)
    ap.add_argument("--font", default=None)
    a = ap.parse_args()

    path = a.font
    if not path:
        for p in CANDIDATES:
            if os.path.exists(p):
                path = p
                break
    if not path:
        raise SystemExit("no monospace font found; pass --font")

    font = ImageFont.truetype(path, a.size)

    # Cell size from the widest/tallest glyph, so nothing is clipped.
    cw = ch = 0
    top = 10 ** 9
    for cp in range(FIRST, LAST + 1):
        box = font.getbbox(chr(cp))
        if box is None:
            continue
        cw = max(cw, box[2])
        ch = max(ch, box[3])
        top = min(top, box[1])
    # advance width is what makes it monospace; use it, not the ink box
    adv = int(round(font.getlength("M")))
    cw = max(cw, adv)
    ch += 1

    n = LAST - FIRST + 1
    img = Image.new("L", (cw * n, ch), 0)
    d = ImageDraw.Draw(img)
    for i, cp in enumerate(range(FIRST, LAST + 1)):
        d.text((i * cw, 0), chr(cp), fill=255, font=font)

    px = img.tobytes()
    with open(a.out, "w") as f:
        f.write("/* Generated by rccars_re/gen_font.py -- do not edit.\n"
                " *\n"
                " * ASCII %d..%d baked from %s at %d px, one row of %d cells,\n"
                " * one coverage byte per texel. Uploaded as GL_ALPHA and drawn as\n"
                " * textured quads -- see ui.c.\n"
                " *\n"
                " * BAKED IN so the START menu cannot fail to draw: font.h is in the\n"
                " * binary and needs no asset to come up.\n"
                " *\n"
                " * This header used to claim the game ships no reusable font. It has\n"
                " * TWO -- Language/English/Smash20.csi and Smash26.csi, 90 glyphs each\n"
                " * on a 10 x 9 atlas, with their character order in a .dat beside them\n"
                " * and their metrics in Settings/smash20.ini / smash26.ini. The old\n"
                " * claim was made over Textures.1/2/3 and Interface.sb and never\n"
                " * re-checked against the one directory that had them; see traps.md.\n"
                " * race_ui.c draws the in-race HUD in the engine's own letters. */\n"
                % (FIRST, LAST, os.path.basename(path), a.size, n))
        f.write("#ifndef FONT_H\n#define FONT_H\n\n")
        f.write("#define FONT_FIRST %d\n#define FONT_LAST  %d\n" % (FIRST, LAST))
        f.write("#define FONT_CW    %d\n#define FONT_CH    %d\n"
                "#define FONT_COUNT %d\n\n" % (cw, ch, n))
        f.write("static const unsigned char FONT_PIX[%d] = {\n" % len(px))
        for i in range(0, len(px), 24):
            f.write("    " + ",".join(str(b) for b in px[i:i + 24]) + ",\n")
        f.write("};\n\n#endif\n")

    print(f"{os.path.basename(path)} @ {a.size}px -> {a.out}")
    print(f"  cell {cw}x{ch}, {n} glyphs, atlas {cw*n}x{ch} = {len(px):,} bytes")


if __name__ == "__main__":
    main()
